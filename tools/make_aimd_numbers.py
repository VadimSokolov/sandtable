"""Generate the congestion-signal macros: what a refusal is worth when something consumes it.

The manuscript said admission control's second half, telling the requester, was a small positive
increment over freeing the slot. This battery shows it is NEGATIVE past the collapse span unless
the vehicle has a rule for responding to it, and strongly positive once it does. Every number the
corrected passage quotes is produced here.

    python3 tools/make_aimd_numbers.py

Writes `report/gen/aimd_numbers.tex` and appends a traceable block to `report/results/numbers.txt`.
"""
from __future__ import annotations

import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from make_queue_numbers import ROOT, paired  # noqa: E402


def agree(hi: dict, lo: dict) -> tuple[float, float, int, int]:
    """Like `paired`, but the third value counts blocks agreeing with the effect's OWN sign.

    `make_queue_numbers.paired` returns blocks with a POSITIVE difference, which is agreement only
    when the effect is positive. Reporting that for a negative effect inverts the sign-consistency
    statistic and would understate exactly the contrasts that show a cost.
    """
    d = [a - b for a, b in zip(hi["vals"], lo["vals"], strict=True)]
    n = len(d)
    mean = sum(d) / n
    var = sum((x - mean) ** 2 for x in d) / (n - 1)
    t = mean / ((var / n) ** 0.5) if var > 0 else float("inf")
    return mean, t, sum(1 for x in d if x * mean > 0), n


LOG = "st-aimd-9446095.out"
SPAN = {"4": "Four", "6": "Six", "8": "Eight", "10": "Ten", "12": "Twelve"}
SEC = {"Clear": "rung 0", "Jam": "rung 2"}


def read() -> list[dict]:
    out, major = [], ""
    for line in (ROOT / "report" / "data" / "queue" / LOG).read_text().splitlines():
        if line.startswith("###"):
            major = line.lstrip("# ").strip()
            continue
        m = re.match(r"AR_ROW arm=(\S+)(?: (\S+?)=(\S+))? mean=([-\d.eE+]+)(?: vals=(\S+))?", line)
        if m:
            arm, _, val, mean, vals = m.groups()
            out.append({"sec": major, "arm": arm, "val": val or "", "mean": float(mean),
                        "vals": [float(v) for v in vals.split(",")] if vals else []})
    return out


def main() -> None:
    rs = read()

    def get(sec, arm, val):
        hits = [r for r in rs if sec.lower() in r["sec"].lower()
                and r["arm"] == arm and r["val"] == val]
        if not hits:
            sys.exit(f"no row for {sec!r} arm={arm} n={val}")
        return hits[0]

    m: dict[str, str] = {}
    for rtag, rung in SEC.items():
        for metric, mtag in (("operator_goodput", "Good"), ("success", "Succ")):
            sec = f"{rung} ({metric})"
            for n, ntag in SPAN.items():
                for arm in ("blind", "refund", "admit", "aimd"):
                    m[f"ai{mtag}{rtag}{arm.capitalize()}{ntag}"] = f"{get(sec, arm, n)['mean']:.3f}"
                eff, t, w, N = agree(get(sec, "aimd", n), get(sec, "admit", n))
                m[f"ai{mtag}{rtag}Gain{ntag}"] = f"{eff:+.3f}"
                m[f"ai{mtag}{rtag}Gain{ntag}T"] = f"{t:.1f}"
                m[f"ai{mtag}{rtag}Gain{ntag}Blocks"] = str(w)
                # What telling the requester is worth with NO response rule: the sign is the point.
                eff2, t2, w2, _ = agree(get(sec, "admit", n), get(sec, "refund", n))
                m[f"ai{mtag}{rtag}Tell{ntag}"] = f"{eff2:+.3f}"
                m[f"ai{mtag}{rtag}Tell{ntag}T"] = f"{t2:.1f}"
    m["aiBlocks"] = str(len(get("rung 0 (operator_goodput)", "aimd", "8")["vals"]))
    gen = ROOT / "report" / "gen" / "aimd_numbers.tex"
    gen.write_text("% AUTO-GENERATED by tools/make_aimd_numbers.py -- do not edit.\n"
                   + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in m.items()))
    res = ROOT / "report" / "results" / "numbers.txt"
    body = res.read_text()
    tag = f"\n\nCongestion-signal numbers (source: tools/make_aimd_numbers.py over {LOG})\n"
    body = body.split(tag)[0] + tag + "=" * 78 + "\n"
    body += "".join(f"\\{k} = {v}\n" for k, v in m.items())
    res.write_text(body)
    print(f"wrote {gen} and appended {len(m)} numbers to {res}")


if __name__ == "__main__":
    main()
