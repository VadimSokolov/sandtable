"""CR-69: the span at which mission success stops being able to resolve anything.

Runs the published centerpiece scenario with no treatment across span and reports mission success
beside blue loss. Success saturates at exactly 1.0 while loss keeps falling, which is what makes an
`equivalent` verdict on success at large span uninformative rather than informative.

Cheap enough to run in the tool (seven spans, twelve reps, one seed), so the numbers regenerate
from the simulator rather than from a stored log.
"""
from __future__ import annotations

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "src"))

from sandtable.scenario import load_scenario                    # noqa: E402
from sandtable.sim import evaluate                              # noqa: E402

SPANS = (4, 6, 8, 12, 16, 24, 32)
WORD = {4: "Four", 6: "Six", 8: "Eight", 12: "Twelve", 16: "Sixteen", 24: "TwentyFour",
        32: "ThirtyTwo"}
OUT = pathlib.Path(__file__).resolve().parents[1] / "report" / "gen" / "ceiling_numbers.tex"


def main() -> None:
    scn = load_scenario("scenarios/sc_span_control.json")
    succ, loss = {}, {}
    for n in SPANS:
        m = evaluate(scn, n_reps=12, seed=0, params={"n_blue": n})
        succ[n], loss[n] = m["success"], m["blue_loss_frac"]

    # The saturation span: the smallest span at and above which success is pinned at one.
    sat = next(n for n in SPANS if all(succ[j] >= 1.0 for j in SPANS if j >= n))

    rows = [("CeSatSpan", str(sat)), ("CeSatSpanWord", WORD[sat].lower())]
    for n in SPANS:
        rows.append((f"CeSucc{WORD[n]}", f"{succ[n]:.4f}"))
        rows.append((f"CeLoss{WORD[n]}", f"{loss[n]:.4f}"))
    # The whole point in one number: loss still moves by this factor across the saturated range.
    rows.append(("CeLossRatio", f"{loss[sat] / loss[SPANS[-1]]:.1f}"))

    OUT.write_text("% generated by tools/make_ceiling_numbers.py -- do not edit\n"
                   + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in rows))
    for k, v in rows:
        print(f"  {k:22s} {v}")


if __name__ == "__main__":
    main()
