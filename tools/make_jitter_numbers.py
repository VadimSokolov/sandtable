"""Generate the retry-jitter macros: why a backoff has to be random, not just long.

CR-27 registered a channel account (vehicles knocked offline together flood back at the link's
recovery edge) and it was refuted: no mean-matched pair on the bursty channel shows a Fano
reduction. The control registered as a throwaway, a memoryless link with no dwell to synchronize
to, showed the effect at full strength. So the synchronization is among the retrying vehicles
themselves, not between them and the channel, and the memoryless arm is the clean demonstration.

    python3 tools/make_jitter_numbers.py

Writes `report/gen/jitter_numbers.tex` and appends a traceable block to `report/results/numbers.txt`.
"""
from __future__ import annotations

import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from make_queue_numbers import ROOT, paired  # noqa: E402


LOG = "st-desync-9446092.out"
SPAN = {"5": "Five", "6": "Six"}


def read() -> list[dict]:
    out, major = [], ""
    for line in (ROOT / "report" / "data" / "queue" / LOG).read_text().splitlines():
        if line.startswith("###"):
            major = line.lstrip("# ").strip()
            continue
        m = re.match(r"AR_ROW arm=(\S+)(?: (\S+?)=(\S+))? mean=([-\d.eE+]+)(?: vals=(\S+))?", line)
        if m:
            arm, _, val, mean, vals = m.groups()
            out.append({"sec": major, "arm": arm, "val": val or "", "mean": float(mean),
                        "vals": [float(v) for v in vals.split(",")] if vals else []})
    return out


def main() -> None:
    rs = read()

    def get(sec, arm, val):
        hits = [r for r in rs if sec.lower() in r["sec"].lower()
                and r["arm"] == arm and r["val"] == val]
        if not hits:
            sys.exit(f"no row for {sec!r} arm={arm} n={val}")
        return hits[0]

    m: dict[str, str] = {}
    # The bursty channel, where the registered account said the effect lived.
    for metric, mtag in (("arrival_fano", "Fano"), ("operator_goodput", "Good")):
        sec = f"D1 jitter against its mean-matched fixed control ({metric})"
        for n, ntag in SPAN.items():
            for width, wtag in (("04", "Narrow"), ("10", "Mid"), ("18", "Wide")):
                eff, t, w, N = paired(get(sec, f"jit{width}", n), get(sec, f"fix{width}", n))
                m[f"jiGe{mtag}{wtag}{ntag}"] = f"{eff:+.4f}"
                m[f"jiGe{mtag}{wtag}{ntag}T"] = f"{t:.1f}"
                m[f"jiGe{mtag}{wtag}{ntag}Blocks"] = str(w)
    # The memoryless channel, registered as a null control and not null.
    for metric, mtag in (("arrival_fano", "Fano"), ("operator_goodput", "Good")):
        sec = f"D2 the null control: no dwell to synchronize to ({metric})"
        for n, ntag in SPAN.items():
            eff, t, w, N = paired(get(sec, "jit18", n), get(sec, "fix18", n))
            m[f"jiBern{mtag}{ntag}"] = f"{eff:+.4f}"
            m[f"jiBern{mtag}{ntag}T"] = f"{t:.1f}"
            m[f"jiBern{mtag}{ntag}Blocks"] = str(w)
            m[f"jiBlocks"] = str(N)
    gen = ROOT / "report" / "gen" / "jitter_numbers.tex"
    gen.write_text("% AUTO-GENERATED by tools/make_jitter_numbers.py -- do not edit.\n"
                   + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in m.items()))
    res = ROOT / "report" / "results" / "numbers.txt"
    body = res.read_text()
    tag = f"\n\nRetry-jitter numbers (source: tools/make_jitter_numbers.py over {LOG})\n"
    body = body.split(tag)[0] + tag + "=" * 78 + "\n"
    body += "".join(f"\\{k} = {v}\n" for k, v in m.items())
    res.write_text(body)
    print(f"wrote {gen} and appended {len(m)} numbers to {res}")


if __name__ == "__main__":
    main()
