"""CR-70: the console requirement does not stop mattering at scale, mission success stops seeing it.

The paper already carries a rule saying a null is only as good as the range the metric had left.
This battery is the demonstration that the rule is not hypothetical, and it is built so that the
obvious objection cannot be raised. That objection is that loss fraction is simply the more
sensitive axis and the effect really did decay with span, in which case switching axes is a metric
preference rather than a finding. W3 answers it without changing the axis at all: it lifts the
CEILING, by strengthening the opposing force, and asks whether mission success recovers the effect
at the span where it had gone quiet. It does.

Every macro here is emitted with its verdict word beside it, because the whole point of the section
is a disagreement between two axes about the same contrast, and a number without its verdict lets a
reader assume the two agreed.
"""
from __future__ import annotations

import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from ar_survey import survey                                    # noqa: E402

ROOT = HERE.parent
LOG = str(ROOT / "report" / "data" / "queue" / "st-loss-9460876.out")
OUT = ROOT / "report" / "gen" / "loss_numbers.tex"

SPANS = ("8", "12", "16", "24", "32")
WORD = {"8": "Eight", "12": "Twelve", "16": "Sixteen", "24": "TwentyFour", "32": "ThirtyTwo"}
V = {"GATE up": "gates up", "GATE down": "gates down",
     "equivalent": "equivalent", "inconclusive": "inconclusive"}


def main() -> None:
    out: list[tuple[str, str]] = []

    # W1. The two axes on the same contrast, span by span. `boundOne` is the free rung, the one
    # CR-66 priced as costing nothing, and it is the rung whose value appeared to decay.
    for metric, tag in (("success", "Succ"), ("blue_loss_frac", "Loss"),
                        ("blue_losses", "Count")):
        c = survey(LOG, "W1", metric, ref="blindUnbound", quiet=True)
        for s in SPANS:
            cell = c.get(("boundOne", s))
            if not cell:
                continue
            eff, t, ag, nb, verdict = cell
            out += [(f"Ls{tag}{WORD[s]}", f"{eff:+.4f}"),
                    (f"Ls{tag}{WORD[s]}V", V.get(verdict, verdict)),
                    (f"Ls{tag}{WORD[s]}T", f"{t:+.2f}"),
                    (f"Ls{tag}{WORD[s]}Blocks", f"{ag}/{nb}")]

    # W3. The same ladder with the ceiling lifted. This is the control that turns a metric
    # preference into a diagnosis, so its numbers are emitted beside W1's for direct comparison.
    c3 = survey(LOG, "W3", "success", ref="blindUnbound", quiet=True)
    for s in SPANS:
        cell = c3.get(("boundOne", s))
        if not cell:
            continue
        eff, t, ag, nb, verdict = cell
        out += [(f"LsLifted{WORD[s]}", f"{eff:+.4f}"),
                (f"LsLifted{WORD[s]}V", V.get(verdict, verdict)),
                (f"LsLifted{WORD[s]}T", f"{t:+.2f}"),
                (f"LsLifted{WORD[s]}Blocks", f"{ag}/{nb}")]

    # The headline pair, named so the prose cannot accidentally quote one without the other.
    w1 = survey(LOG, "W1", "success", ref="blindUnbound", quiet=True)
    wl = survey(LOG, "W1", "blue_loss_frac", ref="blindUnbound", quiet=True)
    if w1.get(("boundOne", "32")):
        eff, _t, ag, nb, _v = w1[("boundOne", "32")]
        # Zero blocks agreeing is not a weak null, it is an instrument with no range left.
        out += [("LsDeadBlocks", f"{ag}/{nb}"), ("LsDeadEff", f"{eff:+.4f}")]
    if wl.get(("boundOne", "32")):
        out.append(("LsAliveEff", f"{wl[('boundOne', '32')][0]:+.4f}"))

    # The guard that fired, and why it was right to. Physics, not a dead knob.
    ident = 0
    for metric in ("success", "blue_loss_frac", "blue_losses"):
        c = survey(LOG, "W2", metric, ref="blindUnbound", quiet=True)
        for s in SPANS:
            a, b = c.get(("admits", s)), c.get(("admitsEdf", s))
            if a and b and a[0] != b[0]:
                ident += 1
    out.append(("LsEdfSeparates", str(ident)))

    OUT.write_text("% generated by tools/make_loss_numbers.py -- do not edit\n"
                   + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in out))
    print(f"wrote {OUT} with {len(out)} macros")


if __name__ == "__main__":
    main()
