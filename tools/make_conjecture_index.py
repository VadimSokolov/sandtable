#!/usr/bin/env python3
"""Rebuild the scoreboard at the top of doc/autoresearch-conjectures.md from the file itself.

The table that used to sit there was written by hand on day one and never updated. Nine thousand
lines below it, C1 had a closed form, C2 had been derived, and C9 had been scored, while the index
still called them in progress, queued and untested. The next session reads the index. This is the
same defect the project keeps cataloguing in code, a convention that was correct when it was typed
and carried forward after it stopped being true, so the fix is not to retype it: it is generated,
and `--check` fails if the file on disk has drifted from what the sections say.

    python3 tools/make_conjecture_index.py [--check]
"""
from __future__ import annotations

import pathlib
import re
import sys

DOC = pathlib.Path(__file__).resolve().parents[1] / "doc" / "autoresearch-conjectures.md"
BEGIN = "<!-- SCOREBOARD:BEGIN generated by tools/make_conjecture_index.py; do not edit by hand -->"
END = "<!-- SCOREBOARD:END -->"
# A verdict is READ, never inferred. An earlier version of this file guessed from keywords in the
# section body and reported CR-75 as holding while its jobs were still queued, which is a worse
# failure than the stale table it replaced: a stale table is visibly old, a fabricated verdict is
# not. A section states its verdict on a line beginning `**Verdict:**` and anything else is
# reported as unread, which is honest and says where to look.
VERDICT = re.compile(r"^\*\*(?:Verdict|Status)(?::\*\*|\*\*:|:)\s*(?P<v>[^.\n]{1,70})", re.M)
UNREAD = "see section"
HEAD = re.compile(r"^## (?P<id>(?:CR-\d+[A-Za-z]?|C\d+))\b[:,]?\s*(?P<rest>.*)$")
LOOK = 40          # lines of the section body a verdict line may appear in


def scan(text: str) -> list[tuple[str, str, str, int]]:
    lines = text.split("\n")
    heads = [(i, m) for i, l in enumerate(lines) if (m := HEAD.match(l))]
    out = []
    for n, (i, m) in enumerate(heads):
        stop = heads[n + 1][0] if n + 1 < len(heads) else len(lines)
        body = "\n".join(lines[i:min(i + LOOK, stop)])
        m2 = VERDICT.search(body)
        verdict = m2.group("v").strip() if m2 else UNREAD
        title = m.group("rest").strip().rstrip(".")
        out.append((m.group("id"), title[:96], verdict, i + 1))
    return out


def render(rows) -> str:
    seen, keep = set(), []
    for r in sorted(rows, key=lambda z: z[3]):
        if r[0] in seen:              # a conjecture scored later keeps its LAST word
            keep = [k for k in keep if k[0] != r[0]]
        seen.add(r[0])
        keep.append(r)
    def order(cid):
        m = re.match(r"([A-Za-z-]+?)-?(\d+)([A-Za-z]?)$", cid)
        return (m.group(1), int(m.group(2)), m.group(3)) if m else (cid, 0, "")
    keep.sort(key=lambda z: order(z[0]))
    body = [BEGIN,
            "",
            f"## Scoreboard ({len(keep)} registered conjectures, "
            f"{sum(1 for k in keep if k[2] != UNREAD)} with a stated verdict)",
            "",
            "Generated from the sections below. Do not edit by hand; run",
            "`python3 tools/make_conjecture_index.py`. The verdict is read from the opening of each",
            "`**Verdict:**` line of each section. A verdict is never inferred from the prose: a",
            "section without that line reads `see section`, because a fabricated verdict is worse",
            "than a missing one. A conjecture scored more than once keeps its last word.",
            "",
            "| # | verdict | line | conjecture |",
            "| --- | --- | --- | --- |"]
    for cid, title, verdict, ln in keep:
        body.append(f"| {cid} | {verdict} | {ln} | {title} |")
    body += ["", END]
    return "\n".join(body)


def main() -> int:
    text = DOC.read_text()
    table = render(scan(text))
    if BEGIN in text:
        a, b = text.index(BEGIN), text.index(END) + len(END)
        new = text[:a] + table + text[b:]
    else:
        anchor = text.index("## Verdict key")
        new = text[:anchor] + table + "\n\n" + text[anchor:]
    if "--check" in sys.argv:
        if new != text:
            print("conjecture index is stale; run tools/make_conjecture_index.py")
            return 1
        print("conjecture index is current")
        return 0
    DOC.write_text(new)
    print(f"scoreboard rebuilt: {len(scan(text))} sections scanned")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
