"""Generate the burst-policy macros: what a refunding console is worth when arrivals cluster.

`refund` was measured on a memoryless link. A real radio fades in bursts, which delivers the
console a cluster at each recovery edge rather than a steady stream. This script reads the
policy-by-channel battery and produces refund's value at matched span on each channel, and the
difference between them, which is the quantity the discussion claims.

    python3 tools/make_burst_numbers.py

Writes `report/gen/burst_numbers.tex` and appends a traceable block to `report/results/numbers.txt`.
"""
from __future__ import annotations

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from make_queue_numbers import ROOT, paired, row, rows  # noqa: E402

LOG = "st-policyburst-9445271.out"
SEC = {"Succ": "policyburst START Q1", "Good": "Q2 the same on the queue"}
CHAN = {"Bern": "bern", "Ge": "co", "Magic": "mg"}
# LaTeX control sequences cannot contain digits, so spans are spelled.
SPAN = {"5": "Five", "6": "Six", "8": "Eight", "10": "Ten"}


def _did(rs, sec, n):
    """Refund's extra value on the clustered channel over the memoryless one, paired by block.
    Both channels deliver at the same marginal rate by construction, so this difference removes
    the level of service and leaves the arrival PATTERN."""
    g = [a - b for a, b in zip(row(rs, sec, "co_ref", n)["vals"],
                               row(rs, sec, "co_blind", n)["vals"], strict=True)]
    e = [a - b for a, b in zip(row(rs, sec, "bern_ref", n)["vals"],
                               row(rs, sec, "bern_blind", n)["vals"], strict=True)]
    d = [x - y for x, y in zip(g, e, strict=True)]
    n_ = len(d)
    mean = sum(d) / n_
    var = sum((x - mean) ** 2 for x in d) / (n_ - 1)
    t = mean / ((var / n_) ** 0.5) if var > 0 else float("inf")
    return mean, t, sum(1 for x in d if x * mean > 0), n_


def main() -> None:
    rs = rows(LOG)
    m: dict[str, str] = {}
    for mtag, sec in SEC.items():
        for n, ntag in SPAN.items():
            for ctag, pre in CHAN.items():
                eff, t, w, _ = paired(row(rs, sec, f"{pre}_ref", n), row(rs, sec, f"{pre}_blind", n))
                m[f"bu{mtag}{ctag}{ntag}"] = f"{eff:+.3f}"
                m[f"bu{mtag}{ctag}{ntag}T"] = f"{t:.1f}"
            dm, dt, dw, dn = _did(rs, sec, n)
            m[f"buDid{mtag}{ntag}"] = f"{dm:+.3f}"
            m[f"buDid{mtag}{ntag}T"] = f"{dt:.1f}"
            m[f"buDid{mtag}{ntag}Blocks"] = str(dw)
            m[f"buDid{mtag}{ntag}N"] = str(dn)
    gen = ROOT / "report" / "gen" / "burst_numbers.tex"
    gen.write_text("% AUTO-GENERATED by tools/make_burst_numbers.py -- do not edit.\n"
                   + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in m.items()))
    res = ROOT / "report" / "results" / "numbers.txt"
    body = res.read_text()
    tag = ("\n\nBurst-policy numbers "
           f"(source: tools/make_burst_numbers.py over report/data/queue/{LOG})\n")
    body = body.split(tag)[0] + tag + "=" * 78 + "\n"
    body += "".join(f"\\{k} = {v}\n" for k, v in m.items())
    res.write_text(body)
    print(f"wrote {gen} and appended {len(m)} numbers to {res}")


if __name__ == "__main__":
    main()
