"""Generate the CR-16 (service-order) numbers the paper quotes.

Three numbers, from three different kinds of evidence, none of them typed:

  qTriageSpread  the full-tier spread across service-order arms at the cell where the effect would
                 be largest, read from the run log
  qTriageSeen    the terrain-difficulty spread ACROSS THE SUPERVISED VEHICLES, measured by running
                 missions with the ordering helper instrumented
  qTriageMap     the terrain-difficulty range available across the whole map, for contrast

The second and third are the diagnosis: the arms reorder, but they sort on a signal a single
formation on a single route barely presents.

    PYTHONPATH=src python3 tools/make_triage_numbers.py
"""
from __future__ import annotations

import pathlib
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from make_queue_numbers import rows                      # noqa: E402
from sandtable import c2, sim, world as W                # noqa: E402
from sandtable.scenario import Scenario, load_scenario   # noqa: E402
from sandtable.seeding import make_rng                   # noqa: E402

SEEDS = range(8)


def arm_spread() -> float:
    """Full-tier spread across the three service-order arms at the strongest-coupling cell."""
    rs = rows("st-triagefull-9442679.out")
    means = [r["mean"] for r in rs if "y1" in r["sec"].lower()]
    if len(means) != 3:
        sys.exit(f"expected 3 Y1 arms, found {len(means)}")
    return max(means) - min(means)


def observed_spread() -> float:
    """Difficulty spread across the vehicles the operator is supervising, over live runs.

    Measured rather than assumed: the ordering arms are only as strong as the dispersion they sort
    on, so a null is uninterpretable without this number.
    """
    scn = load_scenario(ROOT / "scenarios" / "sc_span_control.json")
    p = dict(scn.params, control_mode="direct", n_blue=8, terrain_demand=2)
    scn = Scenario(**{**scn.__dict__, "params": p})

    seen: list[float] = []
    orig = c2.service_order

    def spy(op, blue, difficulty, rng):
        if difficulty and len(blue) > 1:
            d = np.array([difficulty.get(int(i), 0.0) for i in blue])
            seen.append(float(d.max() - d.min()))
        return orig(op, blue, difficulty, rng)

    c2.service_order = spy
    try:
        for s in SEEDS:
            sim.run_mission(scn, seed=s)
    finally:
        c2.service_order = orig
    return float(np.mean(seen))


def map_range() -> float:
    scn = load_scenario(ROOT / "scenarios" / "sc_span_control.json")
    d = 1.0 - W.build_world(scn, make_rng(0, scn.id)).speed
    return float(d.max() - d.min())


def main() -> None:
    m = {
        "qTriageSpread": f"{100 * arm_spread():.1f}",
        "qTriageSeen":   f"{observed_spread():.3f}",
        "qTriageMap":    f"{map_range():.3f}",
    }
    gen = ROOT / "report" / "gen" / "triage_numbers.tex"
    gen.write_text("% AUTO-GENERATED by tools/make_triage_numbers.py -- do not edit.\n"
                   + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in m.items()))

    res = ROOT / "report" / "results" / "numbers.txt"
    body = res.read_text()
    tag = "\n\nService-order numbers (source: tools/make_triage_numbers.py)\n"
    body = body.split(tag)[0]
    body += tag + "=" * 78 + "\n"
    body += "".join(f"\\{k} = {v}\n" for k, v in m.items())
    res.write_text(body)
    print(f"wrote {gen}: " + ", ".join(f"{k}={v}" for k, v in m.items()))


if __name__ == "__main__":
    main()
