"""CR-64: the exclusion fix is a counter the console keeps about itself, not a field in the message.

`round_robin` serves whoever has been served least. It reads nothing about the request: no deadline,
no timestamp, no difficulty, only a counter the console already has. The question is whether that
free rule reaches what the deadline field reaches, and where it does not.

The zero-base guard fires on `starved_frac` here and the prose has to respect it: earliest-deadline
order reads exactly zero at four of six spans, so a relative gate against it is unreadable and the
honest statement is that the two agree to four decimals, not that a gate confirmed they agree.
"""
from __future__ import annotations

import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from ar_survey import survey                                    # noqa: E402

ROOT = HERE.parent
L1 = str(ROOT / "report" / "data" / "queue" / "st-roundrobin-9459574.out")
L2 = str(ROOT / "report" / "data" / "queue" / "st-roundrobin2-9459575.out")
OUT = ROOT / "report" / "gen" / "rr_numbers.tex"

T1 = "T1 the zero-information rule against arrival order and against the field"
T2 = "T2 the same four rules on a console that cannot refuse"
T6 = "T6 where there is no scheduling problem, no rule may win"
SPANS = ("4", "6", "8", "12", "16", "24")
WORD = {"4": "Four", "6": "Six", "8": "Eight", "12": "Twelve", "16": "Sixteen", "24": "TwentyFour"}
V = {"GATE up": "gates up", "GATE down": "gates down",
     "equivalent": "equivalent", "inconclusive": "inconclusive"}


def _con(log, sec, metric, ref, arm, spans=SPANS):
    c = survey(log, sec, metric, ref=ref, quiet=True)
    return {s: c.get((arm, s)) for s in spans} if c else {}


def main() -> None:
    out: list[tuple[str, str]] = []

    # T1. Each rule against arrival order, the default, on an admitting console with a mixed fleet.
    for arm, tag in (("roundRobin", "Rr"), ("edf", "Edf"), ("random", "Rand")):
        for metric, mt in (("starved_frac", "Excl"), ("served_per_step", "Srv")):
            cells = _con(L1, T1, metric, "fcfs", arm)
            for s in ("12", "16", "24"):
                if cells.get(s):
                    eff, _t, _a, _n, verdict = cells[s]
                    out += [(f"Rn{tag}{mt}{WORD[s]}", f"{eff:+.4f}"),
                            (f"Rn{tag}{mt}{WORD[s]}V", V.get(verdict, verdict))]

    # The comparison the section exists for: the free rule against the one that costs a field.
    for metric, mt in (("starved_frac", "Excl"), ("served_per_step", "Srv")):
        cells = _con(L1, T1, metric, "edf", "roundRobin")
        worst = max((abs(c[0]) for c in cells.values() if c), default=None)
        if worst is not None:
            out.append((f"RnFreeVsField{mt}", f"{worst:.4f}"))
        for s in ("16", "24"):
            if cells.get(s):
                eff, _t, _a, _n, verdict = cells[s]
                out += [(f"RnFreeVsField{mt}{WORD[s]}", f"{eff:+.4f}"),
                        (f"RnFreeVsField{mt}{WORD[s]}V", V.get(verdict, verdict))]

    # Levels, so the reader can see the collapse the rules are being asked to fix.
    lv = survey(L1, T1, "starved_frac", quiet=True)
    if lv:
        for arm, tag in (("fcfs", "Fcfs"), ("roundRobin", "Rr"), ("edf", "Edf")):
            if arm in lv:
                out.append((f"RnLevel{tag}", f"{lv[arm][-1]:.4f}"))

    # T2. The precondition, and it is the amendment that inverted the original conjecture. On a
    # console that cannot refuse, no discipline is worth recommending: the free rule and arrival
    # order end at the same place and the deadline field ends WORSE than either.
    lv2 = survey(L1, T2, "starved_frac", quiet=True)
    if lv2:
        for arm, tag in (("fcfs", "Fcfs"), ("roundRobin", "Rr"), ("edf", "Edf"), ("random", "Rand")):
            if arm in lv2:
                out.append((f"RnBlind{tag}", f"{lv2[arm][-1]:.4f}"))
        if "edf" in lv2 and "fcfs" in lv2:
            out.append(("RnBlindFieldWorse",
                        "yes" if lv2["edf"][-1] > lv2["fcfs"][-1] else "no"))

    # T6. The control. Where there is no scheduling problem no rule may win, and if one did the
    # section would be measuring something other than scheduling.
    lv6 = survey(L2, T6, "starved_frac", quiet=True)
    if lv6:
        out.append(("RnControlMax", f"{max(max(v) for v in lv6.values()):.4f}"))

    OUT.write_text("% generated by tools/make_rr_numbers.py -- do not edit\n"
                   + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in out))
    for k, v in out:
        print(f"  {k:26s} {v}")
    print(f"\n{len(out)} macros -> {OUT}")


if __name__ == "__main__":
    main()
